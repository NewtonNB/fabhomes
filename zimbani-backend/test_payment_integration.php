<?php

require __DIR__ . '/vendor/autoload.php';

$app = require_once __DIR__ . '/bootstrap/app.php';
$kernel = $app->make(Illuminate\Contracts\Console\Kernel::class);
$kernel->bootstrap();

use App\Models\Client;
use App\Models\PaymentGatewayConfig;
use App\Models\PaymentIntent;
use App\Models\SavingsAccount;
use App\Services\PaymentProcessingService;

echo "=== Testing Phase 10 Day 1: Unified Payment Gateway Adapters & Dynamic PaymentIntents ===\n\n";

$service = app(PaymentProcessingService::class);

// Test 1: Seed & Retrieve Gateway Configs
echo "1. Testing Gateway Configuration Seeding...\n";
$service->seedInitialGateways();
$gateways = $service->getGatewayConfigs();
assert(count($gateways) >= 5, "At least 5 gateway adapters should be seeded");
echo "   Configured Gateways Count: " . count($gateways) . "\n";
foreach ($gateways as $gw) {
    echo "   - [{$gw['name']}] {$gw['display_name']} (Fee: {$gw['transaction_fee_percentage']}% + {$gw['flat_fee']} UGX)\n";
}
echo "\n";

// Test 2: Create Payment Intent (Flutterwave Card / Mobile Money)
echo "2. Testing Payment Intent Creation (Flutterwave)...\n";
$client = Client::first();
$account = SavingsAccount::first();

$intent = $service->createPaymentIntent([
    'amount' => 2500000.00,
    'currency' => 'UGX',
    'gateway_name' => 'flutterwave',
    'payment_method' => 'card',
    'client_id' => $client?->id,
    'savings_account_id' => $account?->id,
    'client_phone' => '+256772123456',
    'client_email' => 'client@fabhomes.ug',
    'client_name' => 'Diaspora Homebuilder',
    'metadata' => ['purpose' => 'Milestone Substructure Deposit'],
]);
assert(!empty($intent->intent_reference), "Intent reference must be generated");
assert($intent->fee_amount > 0, "Fee should be computed (2.5% of 2.5M = 62,500)");
assert(!empty($intent->gateway_reference), "Gateway reference must be generated by adapter");
assert(!empty($intent->gateway_checkout_url), "Checkout URL should be generated for card payment");
echo "   Intent Reference: {$intent->intent_reference}\n";
echo "   Base Amount: " . number_format($intent->amount, 2) . " {$intent->currency}\n";
echo "   Processing Fee: " . number_format($intent->fee_amount, 2) . " {$intent->currency}\n";
echo "   Total Charge: " . number_format($intent->total_charge_amount, 2) . " {$intent->currency}\n";
echo "   Gateway Reference: {$intent->gateway_reference}\n";
echo "   Status: {$intent->status}\n";
echo "   Checkout URL: " . substr($intent->gateway_checkout_url, 0, 60) . "...\n\n";

// Test 3: Confirm Payment Intent & Post to Dual-Entry Ledger
echo "3. Testing Payment Intent Confirmation & Ledger Settlement...\n";
$initialBalance = $account ? (float) $account->current_balance : 0;
$confirmedIntent = $service->confirmPaymentIntent($intent->id, ['auth_code' => 'AUTH-SUCCESS-8819']);
assert($confirmedIntent->status === 'succeeded', "Status should be succeeded");
assert(!empty($confirmedIntent->payment_id), "Official payment record must be created");

if ($account) {
    $account->refresh();
    echo "   Savings Account Previous Balance: " . number_format($initialBalance, 2) . " UGX\n";
    echo "   Savings Account New Balance: " . number_format($account->current_balance, 2) . " UGX\n";
    assert($account->current_balance > $initialBalance, "Account balance must be incremented by amount");
}
echo "   Official Payment ID: {$confirmedIntent->payment_id}\n";
echo "   Settled At: {$confirmedIntent->succeeded_at}\n\n";

// Test 4: Create MTN Mobile Money Direct STK Push Intent
echo "4. Testing MTN MoMo Direct STK Push Intent...\n";
$momoIntent = $service->createPaymentIntent([
    'amount' => 500000.00,
    'currency' => 'UGX',
    'gateway_name' => 'mtn_momo',
    'payment_method' => 'mobile_money',
    'client_id' => $client?->id,
    'client_phone' => '+256772998877',
    'client_name' => 'MTN Subscriber',
]);
assert($momoIntent->gateway_name === 'mtn_momo', "Gateway should be mtn_momo");
assert($momoIntent->status === 'processing', "Status should be processing for USSD push");
echo "   MTN Intent Reference: {$momoIntent->intent_reference}\n";
echo "   Gateway Response Action: " . ($momoIntent->gateway_response['action_type'] ?? 'N/A') . "\n";
echo "   Prompt Message: " . ($momoIntent->gateway_response['message'] ?? 'N/A') . "\n\n";

// Test 5: Universal Webhook Ingestion & Idempotent Settlement
echo "5. Testing Webhook Ingestion & Idempotent Confirmation...\n";
$webhookPayload = [
    'event' => 'charge.completed',
    'data' => [
        'id' => 9918237,
        'tx_ref' => $momoIntent->intent_reference,
        'flw_ref' => 'FLW-MOMO-882194',
        'status' => 'successful',
        'amount' => 500000.00,
        'currency' => 'UGX',
        'customer' => [
            'phone_number' => '+256772998877',
            'email' => 'mtn@fabhomes.ug',
        ],
    ],
];
$webhookResult = $service->handleWebhook('flutterwave', $webhookPayload, ['verif-hash' => 'flw_secret_test_hash']);
assert($webhookResult['success'] === true, "Webhook processing should succeed");
$momoIntent->refresh();
assert($momoIntent->status === 'succeeded', "MTN Intent should be marked succeeded via webhook");
echo "   Webhook Status: {$webhookResult['message']}\n";
echo "   MTN Intent Final Status: {$momoIntent->status}\n";
echo "   Linked Payment ID: {$momoIntent->payment_id}\n\n";

// Test 6: Global Payment Statistics
echo "6. Testing Global Payment Statistics...\n";
$stats = $service->getStatistics();
assert($stats['total_volume'] > 0, "Total payment volume must be greater than zero");
assert($stats['successful_transactions_count'] >= 2, "At least 2 successful transactions should be counted");
echo "   Total Volume Settled: " . number_format($stats['total_volume'], 2) . " UGX\n";
echo "   Total Processing Fees: " . number_format($stats['total_fees'], 2) . " UGX\n";
echo "   Successful Transactions: {$stats['successful_transactions_count']}\n";
echo "   Success Rate: {$stats['success_rate_percentage']}%\n";
echo "   Breakdown by Payment Method:\n";
foreach ($stats['by_payment_method'] as $method => $data) {
    echo "     * {$method}: {$data['count']} txs (" . number_format($data['volume'], 2) . " UGX)\n";
}
echo "   Breakdown by Gateway Driver:\n";
foreach ($stats['by_gateway'] as $gw => $data) {
    echo "     * {$gw}: {$data['count']} txs (" . number_format($data['volume'], 2) . " UGX)\n";
}
echo "\n";

echo "=== All 6 Phase 10 Payment Gateway Integration Test Steps PASSED! ===\n";
